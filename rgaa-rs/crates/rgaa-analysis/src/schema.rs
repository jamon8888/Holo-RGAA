//! JSON Schema export for proofs and plugin-specific `mesures` (P-00 §5).
//!
//! Same mechanism as the MCP tool schemas: a binary dumps a JSON document,
//! CI/regeneration writes it under `types/`, and nothing is hand-copied.

use crate::error::{analysis_error, Result};
use crate::types::Preuve;
use schemars::JsonSchema;
use serde::Serialize;
use serde_json::Value;

/// The `mesures` object emitted by the P-00 echo plugin.
#[derive(Debug, JsonSchema)]
pub struct EchoMesures {
    pub url: String,
    pub message: String,
}

fn to_value(schema: impl Serialize) -> Result<Value> {
    serde_json::to_value(schema)
        .map_err(|error| analysis_error("schemas", format!("schéma invalide : {error}")))
}

/// All schemas needed by consumers, in one deterministic document.
pub fn schemas() -> Result<Value> {
    Ok(serde_json::json!({
        "$comment": "Generated by `cargo run -p rgaa-analysis --bin dump-analysis-schemas`. Do not edit by hand.",
        "preuve": to_value(schemars::schema_for!(Preuve))?,
        "mesures": {
            "echo": to_value(schemars::schema_for!(EchoMesures))?,
        },
    }))
}
