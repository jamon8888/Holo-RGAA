//! Dumps the MCP tool catalog — names, descriptions and JSON Schemas — as
//! one JSON document on stdout.
//!
//! This exists so the published TypeScript types are *derived* from the
//! server rather than transcribed from it. Hand-written client types drift
//! silently: the plugin docs claimed three tools for a six-tool server and
//! named three (`rgaa_analyze`, `rgaa_remediate`, `rgaa_igt`) that no server
//! has ever registered (#161). Types are worse than docs when they rot,
//! because a wrong type compiles.
//!
//! Deliberately a separate binary rather than a flag on `rgaa-mcp`: that
//! binary speaks the stdio MCP protocol on stdout, and anything else
//! written there corrupts the stream.
//!
//! Output is sorted by tool name so regenerating produces a stable diff and
//! CI can assert the committed types are up to date.

use rgaa_mcp::ToolServer;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut tools: Vec<_> = ToolServer::tool_router()
        .list_all()
        .into_iter()
        .map(|tool| {
            serde_json::json!({
                "name": tool.name,
                "description": tool.description,
                "inputSchema": tool.input_schema,
            })
        })
        .collect();
    tools.sort_by(|a, b| a["name"].as_str().cmp(&b["name"].as_str()));

    let document = serde_json::json!({
        "$comment": "Generated by `cargo run -p rgaa-mcp --bin dump-tool-schemas`. Do not edit by hand.",
        "tools": tools,
    });
    println!("{}", serde_json::to_string_pretty(&document)?);
    Ok(())
}
